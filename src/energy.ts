// Энергия: потолок, темп восстановления и вся арифметика от них —
// ЕДИНСТВЕННЫЙ источник правды на клиент и сервер.
//
// ⚠️ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ В ДВУХ КОПИЯХ: src/energy.ts (клиент) и
// server/src/energy.ts (сервер). Общего пакета в проекте нет и завести его
// дёшево нельзя: tsconfig.app.json включает только "src", у сервера
// rootDir "./src" — импорт наружу не компилируется ни с одной стороны.
// Копии обязаны совпадать БАЙТ В БАЙТ, сверка — `python tools/check_potion_sync.py`
// (read-only, сравнивает sha256 всех известных пар), гонять ПЕРЕД деплоем
// сервера. Тот же приём и та же плата, что у src/potions.ts, src/consumables.ts,
// src/upgrades.ts, src/scrolls.ts и src/skillLevels.ts.
//
// ⚠️ ИМПОРТОВ ЗДЕСЬ НЕТ И БЫТЬ НЕ МОЖЕТ — серверный ESM требует расширение
// (`from './game.js'`), клиентский Vite нет, и первая же общая строка импорта
// развела бы копии. Поэтому здесь только числа и функции от чисел: ни Date, ни
// имён колонок. Сервер превращает результат в метку времени сам
// (regenerateEnergy в game.ts), клиент — в число на экране и в таймер
// (liveEnergy/energyCountdown в App.tsx).
//
// ПОЧЕМУ пара появилась (04.10.2026): до неё потолок и шаг были РУЧНОЙ копией —
// `MAX_ENERGY = 100` в App.tsx рядом с `/ 60000` в формуле и такие же числа в
// game.ts. Смена темпа 1/мин → 1/2мин потребовала бы правки в двух местах, и
// разъехались бы они молча: экран отсчитывал бы одно, сервер начислял другое.

/** Потолок энергии. Выше не поднимается ни регенерацией, ни возвратом. */
export const MAX_ENERGY = 100

/**
 * Сколько миллисекунд копится ОДНА единица энергии.
 *
 * 2 минуты — решение дизайнера 04.10.2026 (было 60 000, то есть минута).
 * Полный бак от нуля: 100 × 2 мин = 3 часа 20 минут.
 *
 * ⚠️ Это ЕДИНСТВЕННОЕ место, где живёт темп. И сервер (начисление и перенос
 * остатка), и клиент (число на экране и таймер «+1 через») считают от него;
 * `60000` в коде энергии больше встречаться не должно нигде.
 */
export const ENERGY_REGEN_MS = 120_000

/**
 * Сколько ЦЕЛЫХ единиц накопилось за `elapsedMs`.
 *
 * Отрицательный интервал даёт НОЛЬ, а не отрицательные единицы, и это не
 * перестраховка: ровно здесь жил баг «99 / 100» (04.10.2026). Клиент считает
 * `now - baseAt`, где `now` — состояние React, снятое при МОНТИРОВАНИИ, а
 * `baseAt` — момент ответа логина, то есть ПОЗЖЕ. Пока не придёт следующий тик,
 * разность отрицательна, `Math.floor(-20000 / 120000)` даёт −1, и полная
 * энергия показывалась как 99. Отрицательного времени не бывает — значит и
 * единиц за него не начисляется.
 */
export function energyUnitsGained(elapsedMs: number): number {
  if (!Number.isFinite(elapsedMs) || elapsedMs <= 0) return 0
  return Math.floor(elapsedMs / ENERGY_REGEN_MS)
}

/** Энергия через `elapsedMs` после момента, когда её было `stored`. */
export function energyAfter(stored: number, elapsedMs: number): number {
  return Math.min(MAX_ENERGY, stored + energyUnitsGained(elapsedMs))
}

/**
 * Сколько миллисекунд осталось до СЛЕДУЮЩЕЙ единицы, или null — энергия полна
 * и ждать нечего.
 *
 * Результат лежит в (0, ENERGY_REGEN_MS]: ровно на границе возвращается полный
 * шаг, а не ноль, — «через 0:00» читалось бы как «уже», хотя единица в этот
 * момент как раз начислена и отсчёт пошёл заново.
 */
export function msToNextEnergy(stored: number, elapsedMs: number): number | null {
  if (energyAfter(stored, elapsedMs) >= MAX_ENERGY) return null
  const sinceLastUnit = Math.max(0, elapsedMs) - energyUnitsGained(elapsedMs) * ENERGY_REGEN_MS
  return ENERGY_REGEN_MS - sinceLastUnit
}
