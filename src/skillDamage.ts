// Урон и лечение НАВЫКОВ — ЕДИНСТВЕННАЯ формула на весь клиент, по образцу
// playerAttackDamage (src/playerDamage.ts) и ровно по той же причине: её зовут и
// забег (Explore.tsx, setup()), и строка «что делает» в витрине, сумке и
// карточке навыка, и число на экране не имеет права разойтись с настоящим
// ударом.
//
// ⚠️ ДОЛЕЙ maxHp ЦЕЛИ БОЛЬШЕ НЕТ (02.10.2026). До этого у каждого навыка была
// своя доля максимального HP цели (FIREBALL_DAMAGE_FRAC, ICEBALL_DAMAGE_FRAC,
// DASH_DAMAGE_FRAC, BLEED_FRAC_PER_TICK, HEAL_PULSE_FRAC — все пять УДАЛЕНЫ из
// explore/constants.ts), то есть урон навыка не зависел от героя вовсе: качай
// статы или нет, шар снимал 10% чужого здоровья. Теперь он считается от СТАТОВ
// ГЕРОЯ, и у каждого навыка своя зависимость — решение дизайнера 02.10.2026:
//
//   огненный шар  1.5 × (сила + выносливость)   каждой цели во взрыве, один раз
//   ледяной шар   1 × ловкость                  стан 2 с не меняется
//   рывок         сила + 2 × броня              каждому задетому, один раз
//   кровотечение  0.2 × атака + 0.4 × ловкость  ЗА ТИК (тики не меняются)
//   исцеление     0.8 × выносливость            ЗА ИМПУЛЬС (импульсы не меняются)
//
// Зависимости РАЗНЫЕ намеренно: это та самая «ловкость влияет на скиллы
// ПО-РАЗНОМУ» из CLAUDE.md (Design Decisions) — не один общий множитель на все
// пять, а своя формула у каждого. Ловкость кормит ледяной шар и кровотечение,
// выносливость — огненный шар и исцеление, броня — только рывок.
//
// ⚠️ Числа каждого навыка фиксируются ОДИН РАЗ в начале забега (Explore.tsx,
// рядом с уроном меча) — статы, броня и уровень за забег не меняются, а пересчёт
// на каждое попадание дал бы те же числа ценой работы в тикере.
//
// Что НЕ здесь: доля maxHp ЛОВУШКИ-МИМИКА (CHEST_TRAP_DAMAGE_FRAC,
// explore/constants.ts) — это урон события по ГЕРОЮ, а не навык, и от статов
// героя он не зависит; тайминги навыков (перезарядки, длительность стана, число
// тиков и импульсов) — тоже там, их уровень и статы не трогают.
import { skillPowerMult } from './skillLevels'
import type { SkillBookSkillId } from './consumables'

/**
 * Всё о герое, от чего зависят навыки. Собирается ОДИН раз вызывающим, чтобы
 * пять формул ниже не вытягивали по отдельности пять источников.
 *
 * Ни одно поле не имеет «неизвестного» значения: случай «данных нет» вызывающий
 * обязан обработать САМ и громко (прочерк в строке, отказ старта забега), а не
 * прислать сюда ноль — ноль здесь значит «честный ноль», и перепутать их нельзя
 * (CLAUDE.md, Design Decisions — тихие фолбэки).
 */
export type SkillStats = {
  strength: number
  endurance: number
  agility: number
  /**
   * Итоговая броня героя: надетое + купленные закалки. ТА ЖЕ величина, что режет
   * урон по герою в бою (armorRef в Explore.tsx) и стоит в строке «Броня» на
   * экране «Персонаж» — рывок бьёт сильнее именно от неё.
   */
  armor: number
  /**
   * Урон удара мечом — playerAttackDamage (src/playerDamage.ts), то же число,
   * что в строке «Урон» на «Персонаже».
   *
   * ⚠️ БЕЗ множителя точильного камня: камень множит удар мечом внутри забега
   * (см. attackDamageRef в Explore.tsx), а здесь нужна база, и по двум причинам
   * сразу — камня в магазине и в сумке ещё нет в руках, когда строка «что
   * делает» уже показана, и дизайнер назвал атаку именно как playerAttackDamage.
   */
  attack: number
}

/**
 * Базовое значение навыка ДО множителя уровня, дробное.
 *
 * Одно число на навык, а не «урон» и «лечение» порознь: у четырёх это урон за
 * попадание (у кровотечения — за тик), у heal — лечение за импульс, и природа
 * числа видна по самому навыку.
 *
 * switch по id, а не таблица-объект: шестой навык без ветки НЕ СКОМПИЛИРУЕТСЯ —
 * тот же приём, что у серверных раскладок по колонкам.
 */
function skillBaseValue(skillId: SkillBookSkillId, s: SkillStats): number {
  switch (skillId) {
    // Сила И выносливость: самый дорогой по перезарядке навык, бьёт по площади.
    case 'fireball': return 1.5 * (s.strength + s.endurance)
    // Чистая ловкость, и меньше огненного: ледяной платит уроном за контроль
    // (стан ICEBALL_STUN_MS, он от статов не зависит).
    case 'iceball': return 1 * s.agility
    // Броня входит с двойным весом: рывок — контактный удар телом, и танк в
    // тяжёлом им бьёт ощутимее, чем лёгкий герой.
    case 'dash': return s.strength + 2 * s.armor
    // ЗА ТИК. Единственная формула, где участвует урон меча: slash это удар
    // клинком плюс кровотечение, и клинок в нём слышен.
    case 'slash': return 0.2 * s.attack + 0.4 * s.agility
    // ЗА ИМПУЛЬС. Выносливость — она же задаёт maxHp (HP_PER_ENDURANCE), так
    // что доля вылеченного от полного здоровья остаётся примерно постоянной.
    case 'heal': return 0.8 * s.endurance
  }
}

/**
 * Готовое ЦЕЛОЕ значение навыка: формула × множитель уровня, затем округление.
 *
 * Порядок именно такой (решение дизайнера): множитель уровня применяется к
 * дробной базе, и только результат округляется — иначе на низких статах
 * округление съело бы прибавку уровня целиком.
 *
 * `Math.floor`, а не round/ceil: округление урона никогда не идёт в пользу
 * игрока (CLAUDE.md, Critical Gotchas), и у лечения ровно та же дисциплина —
 * лишний HP из округления герою не достаётся.
 */
export function skillValue(skillId: SkillBookSkillId, s: SkillStats, level: number): number {
  return Math.floor(skillBaseValue(skillId, s) * skillPowerMult(level))
}
