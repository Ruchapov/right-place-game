import { C } from './theme'
import { skillPowerMult } from '../skillLevels'

/**
 * Блок об уровне навыка под строкой «что делает» — ОДИН на три места: карточка
 * навыка на «Персонаже», карточка книги в сумке и карточка книги в магазине.
 *
 * Отдельным компонентом, а не тремя копиями разметки: три копии разошлись бы на
 * первой же правке текста, а текст здесь — единственное, что игрок узнаёт об
 * уровне навыка вообще (02.10.2026 уровень начал усиливать навык, и сказать об
 * этом надо там, где игрок принимает решение — надеть, купить, улучшить).
 *
 * ⚠️ ПРОГРЕСС ПРИМЕНЕНИЙ ЗДЕСЬ НЕ ПОКАЗЫВАЕТСЯ — решение дизайнера 04.10.2026:
 * в интерфейсе его нет НИГДЕ. Прежняя полоса «X / Y» в шапке карточки навыка
 * удалена вместе с самой строкой «Уровень N» оттуда. Счётчик применений
 * продолжает копиться в забеге и расти на сервере, как и раньше — изменился
 * только показ (см. docs/skills.md).
 *
 * Приглушённый текст (C.textDim), а не акцент: это пояснение к уже названным
 * числам, и перетягивать на себя внимание с «что делает» оно не должно.
 */
export default function SkillLevelNote({ level }: { level: number | null }) {
  // Эффект = множитель силы навыка в процентах (уровень 1 — ровно 100%). Та же
  // функция, по которой бой считает урон и лечение (общая пара
  // src/skillLevels.ts <-> server/src/skillLevels.ts), поэтому процент здесь не
  // может разойтись с настоящим усилением.
  const effect = level === null ? null : Math.round(skillPowerMult(level) * 100)
  return (
    <div style={{ fontSize: 11, lineHeight: 1.5, color: C.textDim, marginBottom: 12 }}>
      {/* Уровень неизвестен (сервер его не назвал) — прочерк и прямое слово
          «неизвестен», а не выдуманная единица со стопроцентным эффектом: то же
          правило и та же формулировка, что стояли в шапке карточки до 04.10.2026
          (CLAUDE.md, Design Decisions — тихие фолбэки запрещены). */}
      <div>
        {level === null
          ? 'Уровень навыка: — (эффект неизвестен)'
          : `Уровень навыка: ${level} (эффект ${effect}%)`}
      </div>
      <div>Повысить уровень можно книгой и применяя навык в бою.</div>
    </div>
  )
}
