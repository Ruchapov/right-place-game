// Уровень навыка: во что он превращается и чем растёт — ЕДИНСТВЕННЫЙ источник
// правды по обеим формулам.
//
// ⚠️ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ В ДВУХ КОПИЯХ: src/skillLevels.ts (клиент) и
// server/src/skillLevels.ts (сервер). Общего пакета в проекте нет и завести его
// дёшево нельзя: tsconfig.app.json включает только "src", у сервера
// rootDir "./src" — импорт наружу не компилируется ни с одной стороны.
// Копии обязаны совпадать БАЙТ В БАЙТ, сверка — `python tools/check_potion_sync.py`
// (read-only, сравнивает sha256 всех известных пар), гонять ПЕРЕД деплоем
// сервера. Тот же приём и та же плата, что у src/potions.ts, src/consumables.ts,
// src/upgrades.ts и src/scrolls.ts.
//
// ⚠️ ИМПОРТОВ ЗДЕСЬ НЕТ И БЫТЬ НЕ МОЖЕТ — серверный ESM требует расширение
// (`from './consumables.js'`), клиентский Vite нет, и первая же общая строка
// импорта развела бы копии. Поэтому в файле только ЧИСЛА и функции от чисел: ни
// одного id навыка, ни одного имени колонки. Раскладка «навык → колонка» живёт
// на сервере (runState.ts), множитель применяется на клиенте (explore/entities/
// skills.ts) — обоим хватает уровня числом.
//
// Почему пара нужна, хотя считает по ней только одна сторона каждой формулы:
// множитель применяет КЛИЕНТ (бой целиком у него), порог считает И сервер (рост
// уровня на финише), И клиент (полоса «X / Y» в карточке навыка и строка «что
// делает» в витрине). Разойдись копии — витрина обещала бы одну силу, а забег
// бил другой, причём молча.

/**
 * Делитель корня в множителе силы навыка. 32 — решение дизайнера: отдача
 * убывающая (см. CLAUDE.md, Design Decisions — «прогрессия скиллов с УБЫВАЮЩЕЙ
 * отдачей»), поэтому корень, а не линейный рост.
 */
export const SKILL_POWER_DIVISOR = 32

/**
 * Во сколько раз уровень усиливает навык: `1 + √(уровень − 1) / 32`.
 *
 * Уровень 1 — ровно 1.0 (100%), то есть базовые числа боевых констант. Дальше:
 * 100 ≈ 1.31, 1000 ≈ 1.99, 4000 ≈ 2.98.
 *
 * ⚠️ Умножает ТОЛЬКО урон и лечение (огненный и ледяной шар, рывок, каждый тик
 * кровотечения, исцеление) — решение дизайнера. Перезарядки, длительность
 * заморозки, число тиков кровотечения и импульсов лечения уровень НЕ трогает:
 * иначе уровень менял бы ритм боя, а не силу удара.
 *
 * Негодный уровень (не число, меньше 1) даёт ровно 1 — не «ноль урона» и не
 * NaN: множителем накрыт живой бой, и единственный безопасный ответ на мусор
 * здесь — базовая сила навыка. Сам мусор ловится раньше и громко (readSkillLevels
 * в src/api.ts возвращает null, забег с неизвестными уровнями не стартует).
 */
export function skillPowerMult(level: number): number {
  if (!Number.isFinite(level) || level <= 1) return 1
  return 1 + Math.sqrt(level - 1) / SKILL_POWER_DIVISOR
}

/**
 * База порога применений. 30 — решение дизайнера: первый уровень стоит 30
 * результативных применений, дальше растёт корнем от уровня.
 */
export const SKILL_USES_BASE = 30

/**
 * Сколько РЕЗУЛЬТАТИВНЫХ применений нужно, чтобы с этого уровня перейти на
 * следующий: `round(30 × √уровень)`.
 *
 * Уровень 1 → 30, 2 → 42, 3 → 52, 10 → 95, 100 → 300.
 *
 * Что такое результативное применение — правило клиента (он один знает, попал
 * ли удар): шары, рывок и кровотечение должны задеть хотя бы одного врага,
 * исцеление — реально восстановить больше нуля HP, и не больше одного
 * применения за нажатие. См. docs/skills.md.
 *
 * ⚠️ Всегда НЕ МЕНЬШЕ 1 (при уровне 1 это 30, дальше только растёт) — на этом
 * держится выход из цикла роста (applySkillLevelProgress в server/src/game.ts):
 * нулевой порог означал бы бесконечный уровень за одно применение.
 */
export function skillUsesThreshold(level: number): number {
  if (!Number.isFinite(level) || level <= 1) return SKILL_USES_BASE
  return Math.round(SKILL_USES_BASE * Math.sqrt(level))
}
