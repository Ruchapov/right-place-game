/**
 * Строка механики для витрины, карточки и списка гнёзд. Числа ВЫВОДЯТСЯ из
 * эффекта, а не написаны текстом рядом: два экземпляра одного числа разошлись бы
 * при первой правке баланса, и витрина начала бы обещать не то, что делает забег.
 */
export function consumableEffectLine(spec: Consumable): string {
  switch (spec.effect.kind) {
    case 'attackBonus':
      return `Урон атаки — +${Math.round(spec.effect.frac * 100)}% до конца забега`
    case 'deathSave':
      return `Спасает от смерти — поднимает с ${Math.round(spec.effect.reviveFrac * 100)}% здоровья. Тратится, только если спас`
  }
}

/**
 * Прибавка к урону обычной атаки, долей. 0 — предмет урона не касается.
 * Отдельной функцией, чтобы суммирование множителя (сервер, /run/start-explore)
 * не разбирало union у себя и не забыло новый вид эффекта.
 */
export function consumableAttackBonus(spec: Consumable): number {
  return spec.effect.kind === 'attackBonus' ? spec.effect.frac : 0
}

/**
 * Доля maxHp, с которой предмет поднимает после спасения от смерти, или null —
 * предмет от смерти не спасает.
 */
export function consumableReviveFrac(spec: Consumable): number | null {
  return spec.effect.kind === 'deathSave' ? spec.effect.reviveFrac : null
}

/** Запись каталога по id, или null если id не из каталога. */
export function consumableById(id: string): Consumable | null {
  return CONSUMABLES.find((c) => c.id === id) ?? null
}

/**
 * Сколько расходников можно взять в ОДИН забег (число гнёзд подготовки на
 * вкладке «Исследовать»).
 *
 * 5 — из дизайна (docs/items.md, «СЛОТЫ РАСХОДНИКОВ НА ЗАБЕГ»). Здесь, в общем
 * каталоге, а не в вёрстке гнёзд: сервер обязан проверять потолок сам, иначе
 * модифицированный клиент возьмёт в забег сколько захочет.
 *
 * ⚠️ Это НЕ то же, что MAX_CONSUMABLES_PER_PURCHASE (сколько купить за раз) и НЕ
 * MAX_SIPS_PER_RUN (сколько глотков зелья за забег). Три разных потолка, и
 * связывать их одним числом нельзя.
 */
export const RUN_CONSUMABLE_SLOTS = 5

/**
 * Запись каталога по id, если этот предмет РАЗРЕШЕНО брать в забег. Иначе null —
 * и «нет такого id», и «есть, но в гнездо не идёт» дают один отказ намеренно:
 * для вызывающего это одинаково негодный вход, а различать их в тексте ошибки
 * значило бы подсказывать, какие id существуют.
 */
export function runSlotConsumableById(id: string): Consumable | null {
  const spec = consumableById(id)
  if (spec === null || !spec.runSlot) return null
  return spec
}

/**
 * Сколько расходников можно купить ОДНИМ запросом. Своя константа, НЕ общая с
 * зельями (`MAX_POTIONS_PER_PURCHASE`): у расходников своя цена и свой смысл
 * запаса, и связывать два потолка одним числом значило бы менять баланс зелий
 * при правке камня.
 *
 * 10 — как у зелий по той же причине: реально ограничивает золото (1000 × 10 =
 * 10000, заведомо безопасное произведение, до потолка int4 нужны миллионы), а
 * двузначное число помещается в один ряд степпера на карточке.
 */
export const MAX_CONSUMABLES_PER_PURCHASE = 10

/**
 * Сколько штук просят купить: из тела запроса (сервер) или из степпера (клиент).
 * Не целое, меньше 1 или больше потолка — null, то есть ОТКАЗ: строку "3", null,
 * 0, 11 и 2.5 молча приводить к числу нельзя, иначе игрок купит не то, что
 * просил.
 *
 * ⚠️ В отличие от зелий, отсутствующее поле — тоже отказ, а не «одна штука»:
 * у покупки расходника нет старого клиента, чей формат надо сохранять, поэтому
 * count здесь обязателен, и тихо додумывать его незачем.
 */
export function parseConsumableCount(raw: unknown): number | null {
  if (typeof raw !== 'number' || !Number.isInteger(raw)) return null
  if (raw < 1 || raw > MAX_CONSUMABLES_PER_PURCHASE) return null
  return raw
}
