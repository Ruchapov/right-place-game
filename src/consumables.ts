    runSlot: true,
    // Списывается ТОЛЬКО если спас (решение дизайнера). Взять оберег и дойти
    // до конца живым — ничего не стоит, он остаётся на складе.
    spendAt: 'effect',
    effect: { kind: 'deathSave', reviveFrac: 0.5 },
