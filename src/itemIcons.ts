/**
 * Код слота в именах файлов иконок предметов — assets/icons/items/, 36 файлов
 * wpn_t1…amu_t6.
 */
export const SLOT_CODE: Record<string, string> = {
  weapon: 'wpn', helmet: 'hlm', armor: 'arm', gloves: 'glv', boots: 'bts', amulet: 'amu',
}

/**
 * Путь к иконке предмета, либо null — слот неизвестен.
 *
 * null возможен по построению: в схеме Item.slot это свободная строка, не enum.
 * Вызывающий обязан решить, что рисовать (ItemIcon в App.tsx показывает
 * название текстом), а не получить ".../undefined_t3.png".
 */
export function itemIconSrc(slot: string, tier: number): string | null {
  const code = SLOT_CODE[slot]
  if (!code) return null
  return `${import.meta.env.BASE_URL}assets/icons/items/${code}_t${tier}.png`
}
