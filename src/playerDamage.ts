// Урон удара мечом игрока — ЕДИНСТВЕННАЯ формула на весь клиент. Её зовут и
// экран "Персонаж" (App.tsx, строка "Урон"), и забег (Explore.tsx, setup()),
// чтобы число на экране и реальный удар не могли разойтись. Раньше формула
// была записана двумя одинаковыми текстами в двух местах, и оружие не входило
// ни в одну.
//
// weaponDamage — Item.damage надетого оружия, 0 если оружия не надето.
// "Неизвестно" (инвентарь не загружен) сюда НЕ передаётся: этот случай
// вызывающий обязан обработать сам и громко (прочерк на экране, отказ старта
// забега), а не подставить ноль.
//
// У навыков СВОЯ формула на каждый — src/skillDamage.ts, от статов героя
// (до 02.10.2026 они били долей maxHp цели). ЭТУ формулу из них зовёт ровно
// один: кровотечение берёт 0.2 × атаку за тик (slash — это удар клинком
// плюс кровотечение), остальные четыре считаются от статов напрямую.
// ⚠️ Сюда передаётся БАЗА, без множителя точильного камня: камень множит
// только удар мечом и только внутри забега (attackDamageRef в Explore.tsx).
// Сервер урон игрока не считает вовсе.
// upgradeBonus — прибавка от КУПЛЕННЫХ закалок клинка (+2 за покупку). Считает
// её общий каталог улучшений (upgradeBonus('attack', counts), src/upgrades.ts),
// а не эта формула: то же число нужно и экрану «Персонаж», и витрине улучшений
// («Урон 93 → 95»), и забегу. «Улучшения неизвестны» сюда, как и неизвестный
// урон оружия, НЕ передаётся — вызывающий обязан показать прочерк.
export function playerAttackDamage(strength: number, weaponDamage: number, upgradeBonus: number): number {
  return 15 + Math.floor(strength / 2) + weaponDamage + upgradeBonus
}
