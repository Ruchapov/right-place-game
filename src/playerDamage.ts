// Урон удара мечом игрока — ЕДИНСТВЕННАЯ формула на весь клиент. Её зовут и
// экран "Персонаж" (App.tsx, строка "Урон"), и забег (Explore.tsx, setup()),
// чтобы число на экране и реальный удар не могли разойтись. Раньше формула
// была записана двумя одинаковыми текстами в двух местах, и оружие не входило
// ни в одну.
//
// weaponDamage — Item.damage надетого оружия, 0 если оружия не надето.
// "Неизвестно" (инвентарь не загружен) сюда НЕ передаётся: этот случай
// вызывающий обязан обработать сам и громко (прочерк на экране, отказ старта
// забега), а не подставить ноль.
//
// Скиллы эту формулу не используют — они бьют долей maxHp цели
// (src/explore/entities/skills.ts), это отдельное дизайнерское решение.
// Сервер урон игрока не считает вовсе.
export function playerAttackDamage(strength: number, weaponDamage: number): number {
  return 15 + Math.floor(strength / 2) + weaponDamage
}
