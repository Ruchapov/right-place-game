-- AlterTable: soulShards / renounceSeals — запас предметов классов (каталог
-- src/classItems.ts / server/src/classItems.ts, docs/classes.md, «Предметы»).
--
-- soulShards — Осколки души. Падают в забегах с 10 уровня героя (вес 5 в броске
-- «что именно», забран у снаряжения). Ячейку сумки НЕ тратят, как страницы.
-- Продаются за 50 золота (POST /character/sell-class-item).
--
-- renounceSeals — Печати отречения. Падают только с босса, отдельным броском 5%
-- поверх обычной добычи. Ячейку сумки ТРАТЯТ — одна на вид, как книга; при
-- полной сумке выпавшая Печать пропадает. Продаются за 500 золота.
--
-- Тратить их пока не на что: выбора класса, возвышения и отречения в игре ещё
-- нет. Колонки растут только дропом (POST /run/finish-explore) и убывают только
-- продажей.
--
-- По колонке на предмет, а не строки InventoryItem и не Json — та же причина,
-- что у scroll* и book*: видов ровно столько, сколько в каталоге, а счётчику
-- нужен атомарный increment в ТОМ ЖЕ UPDATE, который закрывает забег (иначе
-- повтор финиша выдал бы добычу дважды).
--
-- DEFAULT 0 сразу проставляет 0 всем существующим строкам, отдельный UPDATE не
-- нужен: получить эти предметы до этой миграции никто не мог.
--
-- Здесь ТОЛЬКО ADD COLUMN. Добавление колонки с DEFAULT безопасно для ещё
-- живого старого серверного процесса на Render: он про эти колонки не знает и в
-- SELECT их не перечисляет.
--
-- ⚠️ ПОРЯДОК ВЫКЛАДКИ: сначала эта миграция против боевой БД, потом серверный
-- код, потом фронт. Обратный порядок уронит ЛОГИН: classItemStockOf
-- (runState.ts) читает эти колонки, и Prisma запросит их в КАЖДОМ чтении
-- персонажа.
--
-- ⚠️ Применять против боевой базы — Андрею (server/.env смотрит в прод):
--   cd server && npx prisma migrate deploy
-- и сразу после — npx prisma migrate status (read-only), чтобы увидеть
-- "Database schema is up to date!".
ALTER TABLE "Character" ADD COLUMN "soulShards" INTEGER NOT NULL DEFAULT 0;
ALTER TABLE "Character" ADD COLUMN "renounceSeals" INTEGER NOT NULL DEFAULT 0;
