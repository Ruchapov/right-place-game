-- AlterTable: classId / classTier — класс героя (каталог src/heroClasses.ts /
-- server/src/heroClasses.ts, docs/classes.md, «Выбор, возвышение, отречение»).
--
-- classId — ветка: 'ghoul' (Упырь → Владыка крови), 'sorcerer' (Чародей →
-- Повелитель стихий), 'duelist' (Дуэлянт → Мастер клинка); NULL — класса нет.
-- classTier — ступень: 1 после выбора, 2 после возвышения; 0 — класса нет.
-- Читаются только парой, через heroClassOf (server/src/runState.ts).
--
-- Пишут их три ручки: POST /character/choose-class (с 10 уровня, 5 Осколков
-- души + 2000 золота + надетые книги класса), POST /character/ascend-class (с 30
-- уровня, 50 Осколков + 15000 золота) и POST /character/renounce-class (Печать
-- отречения, класс и ступень сбрасываются целиком). Эффектов класса в бою пока
-- нет: класс хранится и показывается.
--
-- Строка без CHECK и без enum: id классов — строки каталога, как у книг и
-- страниц, и проверяет их parseHeroClassId; испорченную пару heroClassOf
-- называет громко, а не «класса нет».
--
-- DEFAULT сразу даёт всем существующим строкам «класса нет» (NULL и 0),
-- отдельный UPDATE не нужен: выбрать класс до этой миграции никто не мог.
--
-- Здесь ТОЛЬКО ADD COLUMN — безопасно для ещё живого старого серверного
-- процесса на Render: он про эти колонки не знает и в SELECT их не перечисляет.
--
-- ⚠️ ПОРЯДОК ВЫКЛАДКИ: сначала эта миграция против боевой БД, потом серверный
-- код, потом фронт. Обратный порядок уронит ЛОГИН: heroClassOf читает эти
-- колонки, и Prisma запросит их в КАЖДОМ чтении персонажа.
--
-- ⚠️ Применять против боевой базы — Андрею (server/.env смотрит в прод):
--   cd server && npx prisma migrate deploy
-- и сразу после — npx prisma migrate status (read-only), чтобы увидеть
-- "Database schema is up to date!".
ALTER TABLE "Character" ADD COLUMN     "classId" TEXT,
ADD COLUMN     "classTier" INTEGER NOT NULL DEFAULT 0;
