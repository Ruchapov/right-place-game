/*
  Система зелий пяти тиров, ШАГ 2 из 2: удалить старую скалярную колонку.

  ПОЧЕМУ ДВЕ МИГРАЦИИ, А НЕ ОДНА.
  Prisma перечисляет колонки в SELECT поимённо, а деплой на Render не
  мгновенный: между стартом выкладки и остановкой прежнего процесса старый
  серверный код продолжает обслуживать запросы. Урони мы "potionCharges" в
  той же миграции, что добавляла potionT1..T5, этот ещё живой процесс начал
  бы падать на каждом чтении Character — то есть на логине, у всех сразу.
  Поэтому шаг 1 (20260911120000_potion_tiers_add) только ДОБАВИЛ колонки и
  перелил данные, оставив "potionCharges" в таблице нетронутой, а этот шаг
  выполняется ОТДЕЛЬНЫМ заходом — уже после того, как новый сервер
  задеплоен и проверен вживую.

  ДАННЫЕ НЕ ТЕРЯЮТСЯ.
  Значение перелито в "potionT1" ещё первой миграцией:
      UPDATE "Character" SET "potionT1" = "potionCharges";
  С тех пор кодом "potionCharges" не читается и не пишется ни на сервере, ни
  на клиенте (проверено поиском по всему репозиторию перед этой миграцией) —
  колонка держалась исключительно ради совместимости на время выкладки.

  СТАРУЮ МИГРАЦИЮ ПРАВИТЬ НЕЛЬЗЯ.
  Дописать DROP в 20260911120000_potion_tiers_add задним числом бессмысленно
  и опасно: Prisma отмечает миграцию применённой по ИМЕНИ папки в таблице
  _prisma_migrations и содержимое migration.sql заново не перечитывает. На
  проде она уже применена, правка разошлась бы с фактическим состоянием базы
  молча, а следующий "migrate deploy" упал бы с P2022. Нужно другое состояние
  схемы — НОВАЯ миграция поверх, как эта. Тем же уроком продиктована
  20260902140000_re_add_level_column, см. её шапку.

  Warnings:
  - Колонка "potionCharges" и её содержимое будут удалены безвозвратно.
    Актуальные данные живут в "potionT1"..."potionT5".
*/
ALTER TABLE "Character" DROP COLUMN "potionCharges";
