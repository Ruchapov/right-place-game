-- AlterTable: charms — запас оберегов от смерти (расходник, каталог
-- src/consumables.ts / server/src/consumables.ts). Оберег один раз за забег
-- заменяет смерть подъёмом с половины здоровья; покупается через
-- POST /character/buy-consumable, списывается НА ФИНИШЕ и только если сработал
-- (spendAt: 'effect'), в отличие от точильного камня.
--
-- Скалярная колонка, а не Json и не отдельная таблица — та же причина, что у
-- potionT1..T5 и whetstones: видов расходников мало и они фиксированы каталогом,
-- а счётчику нужны атомарные increment/decrement в том же UPDATE, где золото.
--
-- DEFAULT 0 сразу проставляет 0 всем существующим строкам, поэтому отдельный
-- UPDATE для переливки не нужен: нового запаса ни у кого быть не может.
--
-- Здесь ТОЛЬКО ADD COLUMN. Ни DROP, ни переливки данных: добавление колонки с
-- DEFAULT безопасно для ещё живого старого серверного процесса на Render
-- (деплой не мгновенный) — он про эту колонку не знает и в SELECT её не
-- перечисляет, так что читать персонажа продолжит без ошибок.
ALTER TABLE "Character" ADD COLUMN "charms" INTEGER NOT NULL DEFAULT 0;
