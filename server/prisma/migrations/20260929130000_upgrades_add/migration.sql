-- AlterTable: attackUpgrades / armorUpgrades — счётчики купленных улучшений
-- («закалок»): клинок даёт +2 к урону за покупку, броня +1 к броне. Каталог с
-- ценой и шагом — src/upgrades.ts / server/src/upgrades.ts (пара байт-в-байт).
--
-- Хранится КОЛИЧЕСТВО покупок, а не готовая прибавка. Две причины:
--   1) цена следующего улучшения считается именно от счётчика
--      (round(300 × 1.2^N), потолка нет);
--   2) правка шага (+2 / +1) тогда не требует переливки данных — прибавку
--      считает каталог на лету (upgradeBonus).
--
-- DEFAULT 0 сразу проставляет ноль всем существующим строкам: купить улучшение
-- до этой миграции было нельзя, переливка не нужна.
--
-- Здесь ТОЛЬКО ADD COLUMN. Добавление колонки с DEFAULT безопасно для ещё живого
-- старого серверного процесса на Render (деплой не мгновенный) — он про эти
-- колонки не знает и в SELECT их не перечисляет.
--
-- ⚠️ ПОРЯДОК ВЫКЛАДКИ обычный и обязательный: сначала миграция против боевой БД,
-- потом серверный код, потом фронт. Без миграции сервер упадёт на ЛОГИНЕ:
-- upgradesOf перечисляет обе колонки поимённо, и Prisma запросит их в каждом
-- чтении персонажа.
ALTER TABLE "Character" ADD COLUMN "attackUpgrades" INTEGER NOT NULL DEFAULT 0;
ALTER TABLE "Character" ADD COLUMN "armorUpgrades" INTEGER NOT NULL DEFAULT 0;
