/** Запись каталога по id, или null если id не из каталога. */
export function classItemById(id: string): ClassItem | null {
  return CLASS_ITEMS.find((c) => c.id === id) ?? null
}

/**
 * id предмета из тела запроса или из вёрстки, либо null — такого предмета нет.
 * Отдельно от classItemById: ручке продажи приходит unknown из JSON-тела, и
 * приводить его к строке догадкой нельзя.
 */
export function parseClassItemId(raw: unknown): ClassItemId | null {
  if (typeof raw !== 'string') return null
  return (CLASS_ITEM_IDS as readonly string[]).includes(raw) ? (raw as ClassItemId) : null
}
