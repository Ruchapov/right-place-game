// Каталог улучшений («закалок») — ЕДИНСТВЕННЫЙ источник цены, шага, иконок и
// текстов. Улучшение покупается за золото навсегда и поднимает стат героя:
// клинок — урон, броня — броню.
//
// ⚠️ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ В ДВУХ КОПИЯХ: src/upgrades.ts (клиент) и
// server/src/upgrades.ts (сервер). Общего пакета в проекте нет и завести его
// дёшево нельзя: tsconfig.app.json включает только "src", у сервера
// rootDir "./src" — импорт наружу не компилируется ни с одной стороны.
// Копии обязаны совпадать БАЙТ В БАЙТ, сверка — `python tools/check_potion_sync.py`
// (read-only, сравнивает sha256 всех известных пар), гонять ПЕРЕД деплоем
// сервера. Тот же приём и та же плата, что у src/potions.ts и src/consumables.ts.
//
// Имя файла иконки — БЕЗ префикса пути: он добавляется на месте использования
// (`${import.meta.env.BASE_URL}assets/icons/${icon}`), ровно как в potions.ts.
// Писать здесь готовый '/assets/icons/...' НЕЛЬЗЯ: ведущий слэш ломает GitHub
// Pages (сайт живёт в подкаталоге), а BASE_URL приходит из import.meta, которого
// на сервере нет — копии разъехались бы по нему.
//
// Чего здесь НЕТ намеренно: цены ПРОДАЖИ предметов. Она живёт только на сервере
// (`itemSellPrice` в game.ts) и приезжает клиенту полем `sellPrice` у каждой
// строки инвентаря — по образцу TROPHY_GOLD_RATE: передать значением дешевле,
// чем держать ещё одну ручную копию.

/** Какой стат поднимает улучшение. Новое улучшение — новый вариант здесь. */
export type UpgradeKind = 'attack' | 'armor'

/** Сколько улучшений каждого вида уже куплено (колонки Character). */
export type UpgradeCounts = { attack: number; armor: number }

/**
 * Цена ПЕРВОГО улучшения и множитель роста. Решение дизайнера: 300 и ×1.2 за
 * каждое уже купленное ЭТОГО ЖЕ вида, потолка нет.
 *
 * Числа здесь, а не в обработчике покупки: цену показывает клиент, а списывает
 * сервер, и две копии формулы разошлись бы при первой правке баланса — игрок
 * видел бы одну цену, платил другую.
 */
export const UPGRADE_PRICE_BASE = 300
export const UPGRADE_PRICE_GROWTH = 1.2

/**
 * Цена СЛЕДУЮЩЕГО улучшения при `bought` уже купленных этого вида.
 * round, а не floor: так решил дизайнер («round(300 × 1.2^N)»).
 *
 * Потолка нет намеренно — цена растёт быстрее любого дохода сама по себе:
 * 300, 360, 432, 518, 622, 746, 896, 1075, 1290, 1548…
 */
export function upgradePrice(bought: number): number {
  return Math.round(UPGRADE_PRICE_BASE * Math.pow(UPGRADE_PRICE_GROWTH, bought))
}

export type Upgrade = {
  kind: UpgradeKind
  nameRu: string
  /** Имя файла в public/assets/icons (128×128, как у зелий и расходников). */
  icon: string
  /** На сколько поднимает стат ОДНА покупка. */
  step: number
  /** Подпись стата для строки механики: «Урон 93 → 95». */
  statLabel: string
  desc: string
}

/**
 * Каталог. Record по виду, а не массив: и клиент, и сервер обращаются к записи
 * ПО ВИДУ (`UPGRADES[kind]`), и поиск по массиву давал бы `| null`, который
 * пришлось бы обрабатывать в каждом вызывающем — при том что тип UpgradeKind уже
 * гарантирует, что запись есть.
 * Порядок показа задаёт UPGRADE_ORDER ниже: у Record порядка нет.
 */
export const UPGRADES: Record<UpgradeKind, Upgrade> = {
  attack: {
    kind: 'attack',
    nameRu: 'Закалка клинка',
    icon: 'upgrade_attack.png',
    step: 2,
    statLabel: 'Урон',
    desc: 'Кузнец не спрашивает, чья кровь на лезвии. Просто делает его острее.',
  },
  armor: {
    kind: 'armor',
    nameRu: 'Закалка брони',
    icon: 'upgrade_armor.png',
    step: 1,
    statLabel: 'Броня',
    desc: 'Новые заклёпки поверх старых вмятин. Держит — и ладно.',
  },
}

/** Порядок показа в витрине. */
export const UPGRADE_ORDER: UpgradeKind[] = ['attack', 'armor']

/**
 * Вид улучшения из тела запроса или из вёрстки, либо null — такого вида нет.
 * Строку из запроса приводить к UpgradeKind кастом нельзя: неизвестный вид
 * должен стать отказом, а не молча выбрать первое улучшение.
 */
export function parseUpgradeKind(raw: unknown): UpgradeKind | null {
  return raw === 'attack' || raw === 'armor' ? raw : null
}

/**
 * Прибавка к стату от УЖЕ КУПЛЕННЫХ улучшений этого вида.
 *
 * ОДНА функция на оба конца и на все места, где считаются урон и броня
 * (playerAttackDamage на клиенте, totalArmor на клиенте и на старте забега на
 * сервере). Ни одно из них не умножает count на шаг самостоятельно: две копии
 * арифметики разошлись бы, и число на экране «Персонаж» перестало бы совпадать
 * с тем, чем герой бьёт в забеге.
 *
 * ⚠️ Принимает ТОЛЬКО известные счётчики. «Сервер не назвал улучшения» — это не
 * ноль, и подставлять его здесь нельзя: вызывающий обязан сам показать прочерк
 * или отказать в старте забега (см. правило про тихие фолбэки в CLAUDE.md).
 */
export function upgradeBonus(kind: UpgradeKind, counts: UpgradeCounts): number {
  return counts[kind] * UPGRADES[kind].step
}
