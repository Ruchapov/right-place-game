// Каталог расходников — ЕДИНСТВЕННЫЙ источник правды по предметам, которые
// берут с собой в забег и тратят.
//
// ⚠️ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ В ДВУХ КОПИЯХ: src/consumables.ts (клиент) и
// server/src/consumables.ts (сервер). Общего пакета в проекте нет и завести его
// дёшево нельзя: tsconfig.app.json включает только "src", у сервера
// rootDir "./src" — импорт наружу не компилируется ни с одной стороны.
// Копии обязаны совпадать БАЙТ В БАЙТ, сверка — `python tools/check_potion_sync.py`
// (read-only, сравнивает sha256 всех известных пар), гонять ПЕРЕД деплоем
// сервера. Тот же приём и та же плата, что у src/potions.ts.
//
// Имя файла иконки — БЕЗ префикса пути: он добавляется на месте использования
// (`${import.meta.env.BASE_URL}assets/icons/${icon}`), ровно как в potions.ts.
// Писать здесь готовый '/assets/icons/whetstone.png' НЕЛЬЗЯ по двум причинам:
// (1) ведущий слэш ломает GitHub Pages — сайт живёт в подкаталоге
// /right-place-game/, и абсолютный путь отдал бы 404; (2) BASE_URL приходит из
// import.meta, которого на сервере нет, и копии разъехались бы по нему.
//
// Чего здесь НЕТ намеренно: имён колонок БД. Запас каждого расходника лежит в
// своей колонке Character, но клиенту это знать не нужно, а держать детали
// схемы в файле, который обязан быть байт-в-байт, — лишний повод его тронуть.
// Раскладка id → колонка живёт на сервере, в runState.ts рядом с зельями.

/** Идентификаторы расходников. Новый расходник — новый вариант здесь. */
export type ConsumableId = 'whetstone'

export type Consumable = {
  id: ConsumableId
  nameRu: string
  /** Имя файла в public/assets/icons (128×128, как у зелий). */
  icon: string
  /** Цена одной штуки в золоте. Источник правды и для витрины, и для сервера. */
  price: number
  /** Минимальный уровень персонажа для ПОКУПКИ. Проверяется и на сервере. */
  levelRequired: number
  /**
   * Прибавка к урону обычной атаки, ДОЛЯ: 0.3 = +30%. Действует до конца
   * забега. Скиллы её не используют — они бьют долей maxHp цели, это отдельное
   * решение (см. CLAUDE.md, Stat & Leveling).
   */
  attackBonus: number
  desc: string
}

export const CONSUMABLES: Consumable[] = [
  {
    id: 'whetstone',
    nameRu: 'Точильный камень',
    icon: 'whetstone.png',
    price: 500,
    levelRequired: 1,
    attackBonus: 0.3,
    desc: 'Шершавый брусок, сточенный до блеска. Пара движений — и клинок снова помнит, зачем его ковали.',
  },
]

/**
 * Строка механики для витрины и карточки. Число ВЫВОДИТСЯ из attackBonus, а не
 * написано текстом рядом: два экземпляра одного числа разошлись бы при первой же
 * правке баланса, и витрина начала бы обещать не то, что делает забег.
 */
export function consumableEffectLine(spec: Consumable): string {
  return `Урон атаки — +${Math.round(spec.attackBonus * 100)}% до конца забега`
}

/** Запись каталога по id, или null если id не из каталога. */
export function consumableById(id: string): Consumable | null {
  return CONSUMABLES.find((c) => c.id === id) ?? null
}

/**
 * Сколько расходников можно купить ОДНИМ запросом. Своя константа, НЕ общая с
 * зельями (`MAX_POTIONS_PER_PURCHASE`): у расходников своя цена и свой смысл
 * запаса, и связывать два потолка одним числом значило бы менять баланс зелий
 * при правке камня.
 *
 * 10 — как у зелий по той же причине: реально ограничивает золото (500 × 10 =
 * 5000, заведомо безопасное произведение, до потолка int4 нужны миллионы), а
 * двузначное число помещается в один ряд степпера на карточке.
 */
export const MAX_CONSUMABLES_PER_PURCHASE = 10

/**
 * Сколько штук просят купить: из тела запроса (сервер) или из степпера (клиент).
 * Не целое, меньше 1 или больше потолка — null, то есть ОТКАЗ: строку "3", null,
 * 0, 11 и 2.5 молча приводить к числу нельзя, иначе игрок купит не то, что
 * просил.
 *
 * ⚠️ В отличие от зелий, отсутствующее поле — тоже отказ, а не «одна штука»:
 * у покупки расходника нет старого клиента, чей формат надо сохранять, поэтому
 * count здесь обязателен, и тихо додумывать его незачем.
 */
export function parseConsumableCount(raw: unknown): number | null {
  if (typeof raw !== 'number' || !Number.isInteger(raw)) return null
  if (raw < 1 || raw > MAX_CONSUMABLES_PER_PURCHASE) return null
  return raw
}
