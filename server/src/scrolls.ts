/** Запись каталога по id, или null если id не из каталога. */
export function scrollById(id: string): Scroll | null {
  return SCROLLS.find((s) => s.id === id) ?? null
}

/**
 * id страницы из тела запроса или из вёрстки, либо null — такой страницы нет.
 *
 * Отдельно от scrollById: тот принимает string, а ручкам страниц (собрать /
 * продать) приходит unknown из JSON-тела, и приводить его к строке догадкой
 * нельзя.
 */
export function parseScrollId(raw: unknown): ScrollId | null {
  if (typeof raw !== 'string') return null
  return (SCROLL_IDS as readonly string[]).includes(raw) ? (raw as ScrollId) : null
}

/**
 * Страница, из которой собирается эта книга, или null — у книги нет страницы.
 *
 * Обратное к Scroll.bookId. Нужно дропу: он выбирает страницу по навыку, а не
 * по книге, но читатель, у которого на руках id книги (карточка книги, будущий
 * экран навыка), не должен заводить вторую карту книга→страница — она
 * разошлась бы с каталогом при добавлении шестой пары.
 *
 * null возможен по построению (книга, для которой страницу ещё не завели),
 * поэтому тип это признаёт: вызывающий обязан решить, что делать, а не получить
 * выдуманную страницу.
 */
export function scrollForBook(bookId: string): Scroll | null {
  return SCROLLS.find((s) => s.bookId === bookId) ?? null
}
