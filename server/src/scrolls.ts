/**
 * id страниц. По странице на каждый навык, как и книг: пять и пять.
 *
 * Рантайм-список рядом с типом (а не только тип) — по нему работает
 * parseScrollId ниже: тип в рантайме не существует, а проверять id из тела
 * запроса надо именно там.
 */
export const SCROLL_IDS = ['scroll_fire', 'scroll_ice', 'scroll_bleed', 'scroll_heal', 'scroll_dash'] as const
export type ScrollId = typeof SCROLL_IDS[number]

/**
 * id книги, которая собирается из страниц. РУЧНОЙ ДУБЛЬ типа SkillBookId
 * (src/consumables.ts) — см. шапку файла: импортировать сюда нельзя, копии
 * обязаны быть байт-в-байт.
 */
export type ScrollBookId = 'book_fire' | 'book_ice' | 'book_bleed' | 'book_heal' | 'book_dash'

export type Scroll = {
  id: ScrollId
  nameRu: string
  /** Имя файла в public/assets/icons (128×128, как у зелий, книг и расходников). */
  icon: string
  /** Какая книга собирается из SCROLLS_PER_BOOK этих страниц. */
  bookId: ScrollBookId
  desc: string
}

/**
 * Сколько страниц складывается в ОДНУ книгу. Три — решение дизайнера
 * (docs/items.md, «ПРАВИЛО ВМЕСТИМОСТИ»: «три страницы = одна книга»).
 *
 * Живёт в общем каталоге, а не на одной стороне: потолок проверяет СЕРВЕР
 * (фильтр условной записи `страниц >= SCROLLS_PER_BOOK`), а подпись
 * «Собрать книгу (N/3)» рисует по нему клиент. Два экземпляра этого числа
 * разошлись бы, и кнопка обещала бы сборку, которую сервер отвергнет.
 */
export const SCROLLS_PER_BOOK = 3

/**
 * Сколько золота даёт продажа ОДНОЙ страницы. 30 — решение дизайнера.
 *
 * Плоское число, а НЕ доля от цены книги (у книги 1000, выкуп 100 — см.
 * consumableSellPrice): страницы не продаются в магазине вовсе, поэтому «цены
 * покупки», от которой можно было бы считать долю, у них не существует.
 * Выводить её из книги (1000 / 3 / 10 ≈ 33) значило бы связать два числа,
 * которые дизайн связывать не просил.
 *
 * Одно число на клиент и сервер: на кнопке написано ровно то, что начислит
 * POST /character/sell-scroll.
 */
export const SCROLL_SELL_PRICE = 30

