// Чего здесь НЕТ намеренно: имён колонок БД (склад страниц лежит в пяти
// колонках Character.scroll*, раскладка id → колонка живёт на сервере, в
// runState.ts рядом с зельями и книгами) и цены ПОКУПКИ. Страницы НЕ ПРОДАЮТСЯ
// в магазине — решение дизайнера 28.09.2026: они только выпадают в забегах.
